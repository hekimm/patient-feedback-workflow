-- Run after the schema scripts. Existing reference rows are skipped.

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
WHENEVER OSERROR EXIT FAILURE

SET DEFINE OFF;
SET VERIFY OFF;

PROMPT Step 010 - roles and permissions started.

MERGE INTO HGB_ROLES t USING (SELECT 'SYS_ADMIN' ROLE_CODE, 'Sistem Yöneticisi' ROLE_NAME, 'Tüm modül yönetimi' DESCRIPTION FROM dual) s
ON (t.ROLE_CODE = s.ROLE_CODE)
WHEN NOT MATCHED THEN INSERT (ROLE_CODE, ROLE_NAME, DESCRIPTION) VALUES (s.ROLE_CODE, s.ROLE_NAME, s.DESCRIPTION);
MERGE INTO HGB_ROLES t USING (SELECT 'QUALITY_MANAGER' ROLE_CODE, 'Kalite Yöneticisi' ROLE_NAME, 'Dashboard, rapor ve kalite süreçleri' DESCRIPTION FROM dual) s
ON (t.ROLE_CODE = s.ROLE_CODE)
WHEN NOT MATCHED THEN INSERT (ROLE_CODE, ROLE_NAME, DESCRIPTION) VALUES (s.ROLE_CODE, s.ROLE_NAME, s.DESCRIPTION);
MERGE INTO HGB_ROLES t USING (SELECT 'UNIT_MANAGER' ROLE_CODE, 'Birim Sorumlusu' ROLE_NAME, 'Hizmet telafisi ve bölüm aksiyonları' DESCRIPTION FROM dual) s
ON (t.ROLE_CODE = s.ROLE_CODE)
WHEN NOT MATCHED THEN INSERT (ROLE_CODE, ROLE_NAME, DESCRIPTION) VALUES (s.ROLE_CODE, s.ROLE_NAME, s.DESCRIPTION);

MERGE INTO HGB_PERMISSIONS t USING (SELECT 'DASHBOARD_VIEW' PERMISSION_NAME, 'Dashboard' MODULE_NAME FROM dual) s
ON (t.PERMISSION_NAME = s.PERMISSION_NAME)
WHEN NOT MATCHED THEN INSERT (PERMISSION_NAME, MODULE_NAME) VALUES (s.PERMISSION_NAME, s.MODULE_NAME);
MERGE INTO HGB_PERMISSIONS t USING (SELECT 'SURVEY_ADMIN' PERMISSION_NAME, 'Survey' MODULE_NAME FROM dual) s
ON (t.PERMISSION_NAME = s.PERMISSION_NAME)
WHEN NOT MATCHED THEN INSERT (PERMISSION_NAME, MODULE_NAME) VALUES (s.PERMISSION_NAME, s.MODULE_NAME);
MERGE INTO HGB_PERMISSIONS t USING (SELECT 'RECOVERY_MANAGE' PERMISSION_NAME, 'ServiceRecovery' MODULE_NAME FROM dual) s
ON (t.PERMISSION_NAME = s.PERMISSION_NAME)
WHEN NOT MATCHED THEN INSERT (PERMISSION_NAME, MODULE_NAME) VALUES (s.PERMISSION_NAME, s.MODULE_NAME);
MERGE INTO HGB_PERMISSIONS t USING (SELECT 'COMPLIANCE_MANAGE' PERMISSION_NAME, 'Compliance' MODULE_NAME FROM dual) s
ON (t.PERMISSION_NAME = s.PERMISSION_NAME)
WHEN NOT MATCHED THEN INSERT (PERMISSION_NAME, MODULE_NAME) VALUES (s.PERMISSION_NAME, s.MODULE_NAME);

INSERT INTO HGB_ROLE_PERMISSIONS (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM HGB_ROLES r CROSS JOIN HGB_PERMISSIONS p
WHERE r.ROLE_CODE = 'SYS_ADMIN'
  AND NOT EXISTS (SELECT 1 FROM HGB_ROLE_PERMISSIONS rp WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID);

INSERT INTO HGB_ROLE_PERMISSIONS (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM HGB_ROLES r JOIN HGB_PERMISSIONS p ON p.PERMISSION_NAME IN ('DASHBOARD_VIEW', 'RECOVERY_MANAGE')
WHERE r.ROLE_CODE IN ('QUALITY_MANAGER', 'UNIT_MANAGER')
  AND NOT EXISTS (SELECT 1 FROM HGB_ROLE_PERMISSIONS rp WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID);
INSERT INTO HGB_USER_ROLES (USER_ID, ROLE_ID)
SELECT u.USER_ID, u.PRIMARY_ROLE_ID FROM HGB_USERS u
WHERE u.PRIMARY_ROLE_ID IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM HGB_USER_ROLES ur WHERE ur.USER_ID = u.USER_ID AND ur.ROLE_ID = u.PRIMARY_ROLE_ID);

MERGE INTO HGB_SCHEMA_VERSION t
USING (
    SELECT '2026-07-data-01-access' VERSION_CODE, 'Default application roles and permissions' DESCRIPTION
    FROM dual
) s
ON (t.VERSION_CODE = s.VERSION_CODE)
WHEN NOT MATCHED THEN
    INSERT (VERSION_CODE, DESCRIPTION)
    VALUES (s.VERSION_CODE, s.DESCRIPTION);

COMMIT;

PROMPT Step 010 - roles and permissions completed.
