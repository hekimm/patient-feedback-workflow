INSERT INTO HGB_CHANNEL_TEMPLATES (CHANNEL_ID, TEMPLATE_CODE, LANGUAGE_CODE, BODY_TEMPLATE)
SELECT c.CHANNEL_ID, 'SURVEY_INVITE', l.LANG, l.BODY
FROM HGB_CHANNELS c
CROSS JOIN (
    SELECT 'tr' LANG, 'Sayın {{patient_name}}, memnuniyet anketiniz: {{survey_link}}' BODY FROM dual
    UNION ALL SELECT 'en', 'Dear {{patient_name}}, your satisfaction survey: {{survey_link}}' FROM dual
    UNION ALL SELECT 'ar', 'رابط استبيان الرضا: {{survey_link}}' FROM dual
) l
WHERE c.CHANNEL_CODE IN ('SMS', 'WHATSAPP', 'QR', 'PORTAL', 'KIOSK')
  AND NOT EXISTS (
      SELECT 1 FROM HGB_CHANNEL_TEMPLATES ct
      WHERE ct.CHANNEL_ID = c.CHANNEL_ID AND ct.TEMPLATE_CODE = 'SURVEY_INVITE' AND ct.LANGUAGE_CODE = l.LANG
  );

