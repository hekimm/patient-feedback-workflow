DECLARE
    PROCEDURE create_table_if_missing(p_table_name VARCHAR2, p_sql CLOB) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
        FROM user_tables
        WHERE table_name = UPPER(p_table_name);

        IF v_count = 0 THEN
            EXECUTE IMMEDIATE p_sql;
            DBMS_OUTPUT.PUT_LINE('created table ' || p_table_name);
        END IF;
    END;
BEGIN
    create_table_if_missing('HGB_AUDIT_LOGS', q'[
        CREATE TABLE HGB_AUDIT_LOGS (
            AUDIT_LOG_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            ENTITY_NAME VARCHAR2(100) NOT NULL,
            ENTITY_ID NUMBER,
            ACTION_CODE VARCHAR2(100) NOT NULL,
            ACTOR_USER_ID NUMBER,
            PATIENT_ID NUMBER,
            CHANGE_DESCRIPTION NVARCHAR2(1000),
