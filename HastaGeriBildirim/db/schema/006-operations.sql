        )]');

    create_table_if_missing('HGB_KPI_TARGETS', q'[
        CREATE TABLE HGB_KPI_TARGETS (
            KPI_TARGET_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            KPI_CODE VARCHAR2(50) NOT NULL,
            DEPARTMENT_ID NUMBER,
            TARGET_PERIOD VARCHAR2(20) DEFAULT 'MONTH',
            TARGET_VALUE NUMBER(10,2) NOT NULL,
            VALID_FROM DATE DEFAULT SYSDATE,
            VALID_TO DATE,
            CREATED_BY_USER_ID NUMBER,
            CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
        )]');

    create_table_if_missing('HGB_REPORT_EXPORTS', q'[
        CREATE TABLE HGB_REPORT_EXPORTS (
            REPORT_EXPORT_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            REQUESTED_BY_USER_ID NUMBER,
