            REQUESTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
            COMPLETED_AT TIMESTAMP,
            REQUESTED_BY_NOTE NVARCHAR2(1000),
            HANDLED_BY_USER_ID NUMBER,
            RESOLUTION_NOTE NVARCHAR2(1000)
        )]');
END;
